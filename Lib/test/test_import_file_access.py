    def test_shared_code_filename_update(self):
        self.run_script('''
            import _imp
            code = compile('def inner(): return 42', 'old-path', 'exec')
            class LocalFilename(str):
                pass
            inaccessible = code.replace(co_filename=LocalFilename('foreign'))
            def action():
                _imp._fix_co_filename(code, 'new-path')
                assert code.co_filename == 'new-path'
                assert code.co_consts[0].co_filename == 'new-path'
                try:
                    _imp._fix_co_filename(inaccessible, 'forbidden')
                except IllegalThreadAccessException:
                    pass
                else:
                    raise AssertionError('foreign filename metadata acquired')
            run(action)
            assert inaccessible.co_filename == 'foreign'
        ''')

    def test_filesystem_error_types_in_worker(self):
        self.run_script('''
            import _io
            from errno import ENOENT, EEXIST
            from os import stat
            with tempfile.TemporaryDirectory() as directory:
                missing = os.path.join(directory, 'missing')
                def action():
                    assert type(OSError(ENOENT, 'missing')) is FileNotFoundError
                    assert type(OSError(EEXIST, 'exists')) is FileExistsError
                    for read in (lambda: stat(missing),
                                 lambda: _io.open_code(missing)):
                        try:
                            read()
                        except FileNotFoundError as exc:
                            assert exc.errno == ENOENT
                            assert exc.filename == missing
                        else:
                            raise AssertionError('missing file opened')
                run(action)
        ''')

