    def test_native_import_checks_hooks_and_exposed_globals(self):
        self.run_script('''
            import _testlimitedcapi
            import _testinternalcapi
            native_import = _testlimitedcapi.PyImport_Import
            _testinternalcapi.object_declare_synchronized(native_import)
            calls = threading.Channel()
            class LocalHook:
                def __call__(self, *args):
                    calls.put('local hook called')
                    return sys
            def shared_hook(*args):
                calls.put('shared hook called')
                return sys
            for hook in (LocalHook(), shared_hook):
                namespace = {
                    '__builtins__': {'__import__': hook},
                    'native_import': native_import,
                }
                exec('def invoke(): return native_import("sys")', namespace)
                invoke = namespace['invoke']
                def action():
                    try:
                        invoke()
                    except IllegalThreadAccessException:
                        results.put('denied')
                    else:
                        raise AssertionError('foreign hook or globals exposed')
                run(action)
                assert results.get() == 'denied'
            try:
                calls.get()
            except IndexError:
                pass
            else:
                raise AssertionError('import hook called without access')
        ''')


